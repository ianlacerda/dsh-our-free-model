import { useEffect, useState, useSyncExternalStore } from 'react'
import { EXTRA_DICTIONARY } from './i18n-extra'

export type Locale = 'en' | 'pt-BR' | 'es' | 'fr' | 'zh'

export interface LocaleOption {
  id: Locale
  label: string
  flag: string
}

export const LOCALES: LocaleOption[] = [
  { id: 'en', label: 'English', flag: '🇺🇸' },
  { id: 'pt-BR', label: 'Português (Brasil)', flag: '🇧🇷' },
  { id: 'es', label: 'Español', flag: '🇪🇸' },
  { id: 'fr', label: 'Français', flag: '🇫🇷' },
  { id: 'zh', label: '中文', flag: '🇨🇳' },
]

function detectInitialLocale(): Locale {
  try {
    const saved = localStorage.getItem('ofm-locale') as Locale
    if (saved && LOCALES.some(l => l.id === saved)) return saved
  } catch { /* storage unavailable */ }

  const nav = typeof navigator !== 'undefined' ? (navigator.language || '').toLowerCase() : ''
  if (nav.startsWith('pt')) return 'pt-BR'
  if (nav.startsWith('es')) return 'es'
  if (nav.startsWith('fr')) return 'fr'
  if (nav.startsWith('zh')) return 'zh'
  return 'en'
}

let currentLocale: Locale = detectInitialLocale()
if (typeof document !== 'undefined') {
  document.documentElement.lang = currentLocale === 'pt-BR' ? 'pt-BR' : currentLocale === 'zh' ? 'zh-CN' : currentLocale
}
const listeners = new Set<() => void>()

export function getLocale(): Locale {
  return currentLocale
}

export function setLocale(locale: Locale) {
  if (currentLocale === locale) return
  currentLocale = locale
  try {
    localStorage.setItem('ofm-locale', locale)
    document.documentElement.lang = locale === 'pt-BR' ? 'pt-BR' : locale === 'zh' ? 'zh-CN' : locale
  } catch { /* ignore */ }
  listeners.forEach(fn => fn())
  window.dispatchEvent(new CustomEvent('ofm:locale-changed', { detail: locale }))
}

export function useLocale(): [Locale, (next: Locale) => void] {
  const locale = useSyncExternalStore(
    cb => {
      listeners.add(cb)
      return () => listeners.delete(cb)
    },
    getLocale,
    () => 'en' as Locale
  )
  return [locale, setLocale]
}

